// 规范化 region：统一为「省·市」口径，剔除混入的平台名（如“央企招投标”“全国”）
// 原则：仅在项目主体所在地可由公告主体明确认定时才落到市级；无法确证的只保留省级；
//      公告确未载明的，如实写“公告未载明”，不做推测。
